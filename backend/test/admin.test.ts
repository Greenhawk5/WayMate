import { describe, it, expect, beforeEach } from 'vitest';
import { app } from '../src/index.js';
import { createTestD1Database } from './helpers/testDb.js';

describe('Admin API (/api/v1/admin)', () => {
  let db: D1Database;
  const env = () => ({
    DB: db,
    ENVIRONMENT: 'test',
    API_VERSION: 'v1',
    JWT_SECRET: 'test-secret-key-32bytes-for-jwt-signing',
  });

  let ownerToken: string;
  let commanderToken: string;
  let teamLeadToken: string;

  beforeEach(async () => {
    db = createTestD1Database();

    const ownerRes = await app.request(
      '/api/v1/auth/login',
      {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ username: 'owner_demo', password: 'demo123' }),
      },
      env()
    );
    ownerToken = (await ownerRes.json<any>()).data.token;

    const cmdRes = await app.request(
      '/api/v1/auth/login',
      {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ username: 'commander_demo', password: 'demo123' }),
      },
      env()
    );
    commanderToken = (await cmdRes.json<any>()).data.token;

    const leadRes = await app.request(
      '/api/v1/auth/login',
      {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ username: 'patrol_lead_demo', password: 'demo123' }),
      },
      env()
    );
    teamLeadToken = (await leadRes.json<any>()).data.token;
  });

  it('GET /admin/stats succeeds for COMMANDER and OWNER', async () => {
    const resCmd = await app.request(
      '/api/v1/admin/stats',
      { headers: { Authorization: `Bearer ${commanderToken}` } },
      env()
    );
    expect(resCmd.status).toBe(200);
    const jsonCmd = await resCmd.json<any>();
    expect(jsonCmd.success).toBe(true);
    expect(jsonCmd.data.system_status).toBe('OPERATIONAL');
    expect(jsonCmd.data.users.total).toBeGreaterThanOrEqual(3);
    expect(jsonCmd.data.teams.total).toBeGreaterThanOrEqual(1);

    const resOwner = await app.request(
      '/api/v1/admin/stats',
      { headers: { Authorization: `Bearer ${ownerToken}` } },
      env()
    );
    expect(resOwner.status).toBe(200);
  });

  it('GET /admin/stats is forbidden (403) for TEAM_LEAD', async () => {
    const res = await app.request(
      '/api/v1/admin/stats',
      { headers: { Authorization: `Bearer ${teamLeadToken}` } },
      env()
    );
    expect(res.status).toBe(403);
    const json = await res.json<any>();
    expect(json.success).toBe(false);
    expect(json.error.code).toBe('FORBIDDEN');
  });

  it('GET /admin/audit-logs succeeds for OWNER', async () => {
    const res = await app.request(
      '/api/v1/admin/audit-logs',
      { headers: { Authorization: `Bearer ${ownerToken}` } },
      env()
    );
    expect(res.status).toBe(200);
    const json = await res.json<any>();
    expect(json.success).toBe(true);
    expect(Array.isArray(json.data)).toBe(true);
    // There should be login audit records generated by the test setup
    expect(json.data.length).toBeGreaterThanOrEqual(1);
  });

  it('GET /admin/audit-logs is forbidden (403) for COMMANDER', async () => {
    const res = await app.request(
      '/api/v1/admin/audit-logs',
      { headers: { Authorization: `Bearer ${commanderToken}` } },
      env()
    );
    expect(res.status).toBe(403);
    const json = await res.json<any>();
    expect(json.success).toBe(false);
    expect(json.error.code).toBe('FORBIDDEN');
  });
});
